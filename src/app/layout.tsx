import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono } from "next/font/google";

import { SiteFooter } from "@/components/layout/site-footer";
import { SiteHeader } from "@/components/layout/site-header";
import { ThemeScript } from "@/components/layout/theme-script";
import { WebVitals } from "@/components/layout/web-vitals";
import { siteConfig } from "@/config/site";

import "./globals.css";

/**
 * `next/font` downloads and self-hosts these at build time — no runtime request
 * to Google, no layout shift, and the font files are served from our own origin.
 * Each call exposes a CSS variable that globals.css wires into `--font-sans`.
 */
const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
  display: "swap",
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
  display: "swap",
});

export const metadata: Metadata = {
  /**
   * Required for Open Graph and Twitter images to resolve. Without it, relative
   * image paths in metadata are emitted as-is and crawlers cannot fetch them.
   */
  metadataBase: new URL(siteConfig.url),
  title: {
    default: `${siteConfig.name} — Modern tech, thoughtfully chosen`,
    /** Child routes set `title: "Audio"` and get "Audio | Nexus Store". */
    template: `%s | ${siteConfig.name}`,
  },
  description: siteConfig.description,
  applicationName: siteConfig.name,
  openGraph: {
    type: "website",
    siteName: siteConfig.name,
    url: siteConfig.url,
    title: siteConfig.name,
    description: siteConfig.description,
    locale: siteConfig.locale,
  },
  twitter: {
    card: "summary_large_image",
    title: siteConfig.name,
    description: siteConfig.description,
  },
  /**
   * Deliberately NO `robots` key here.
   *
   * "index, follow" is already the default when no robots tag is present, so
   * setting it buys nothing — and it actively causes harm on not-found pages:
   * Next injects its own `<meta name="robots" content="noindex">` there, and a
   * global `index, follow` would emit a second, contradictory tag alongside it.
   * Crawlers are supposed to honour the most restrictive directive, but there
   * is no reason to make them arbitrate. Set `robots` per-route, when a route
   * actually needs to deviate from the default.
   */
};

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#ffffff" },
    { media: "(prefers-color-scheme: dark)", color: "#0d1017" },
  ],
};

/**
 * `LayoutProps<"/">` is generated by `next typegen` (which runs automatically
 * during `next dev` / `next build`). It types `children` and, for routes with
 * parallel slots, every `@slot` prop — so a typo in a slot name is caught at
 * compile time.
 */
export default function RootLayout({ children, modal }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full`}
      // ThemeScript mutates this element's class before React hydrates, which
      // is a server/client mismatch on purpose. Without this, React logs a
      // hydration warning for a difference we created deliberately.
      suppressHydrationWarning
    >
      <head>
        {/*
          Must be in <head> and must be synchronous. Placed in <body> it would
          run after the browser has already painted the unthemed page, which is
          exactly the flash it exists to prevent.
        */}
        <ThemeScript />
      </head>
      <body className="flex min-h-full flex-col">
        <WebVitals />
        <SiteHeader />
        <main className="flex-1">{children}</main>
        {/*
          The `@modal` parallel slot, rendered alongside `children` rather than
          inside it. Both occupy the same layout at the same time — that is what
          a parallel route is. It resolves to `@modal/default.tsx` (null) on
          every route except an intercepted /products/[slug].

          `modal` is typed automatically: `LayoutProps<"/">` picks up every
          `@slot` folder under this layout, so renaming the folder to `@dialog`
          without updating this prop is a compile error.
        */}
        {modal}
        <SiteFooter />
      </body>
    </html>
  );
}
